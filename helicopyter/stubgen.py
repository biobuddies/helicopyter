"""
Generate helicopyter/__init__.pyi from `terraform providers schema -json`.

Deploy code keeps calling the small Block runtime; the stub adds erased-at-runtime types so IDE
autocomplete and basedpyright catch attribute typos offline, with `tofu validate` as the semantic
backstop. Run after `mise tinit` so types match .terraform.lock.hcl, and commit the stub like a
lock file.
"""

